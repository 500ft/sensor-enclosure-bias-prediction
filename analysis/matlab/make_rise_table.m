function make_rise_table(dataDir, outDir)
%MAKE_RISE_TABLE Write the predicted-rise table as LaTeX (booktabs + siunitx).
%   Input: sensor-enclosure-bias-prediction analysis/output/thermal_bias_table.csv.
%   Output: predicted_rise_table.tex, a tabular fragment that \input{}s into a
%   document. Every number is read from the CSV and rounded to 0.1.

opts = detectImportOptions(fullfile(dataDir, 'thermal_bias_table.csv'), 'CommentStyle', '#');
opts = setvartype(opts, {'variant_id', 'variant_name'}, 'string');
T = readtable(fullfile(dataDir, 'thermal_bias_table.csv'), opts);

wind = 0.5;
ids  = ["V0", "V0P", "V1", "V2"];
G    = [800 1000];
pick = @(id, g, col) T.(col)(T.variant_id == id & T.g_w_m2 == g & abs(T.wind_m_s - wind) < 1e-9);

rows = strings(numel(ids), 1);
for i = 1:numel(ids)
    nm = T.variant_name(find(T.variant_id == ids(i), 1));
    v = [pick(ids(i), G(1), 'delta_t_degc'), pick(ids(i), G(2), 'delta_t_degc'), ...
         pick(ids(i), G(1), 'rh_err_pct'),   pick(ids(i), G(2), 'rh_err_pct')];
    assert(numel(v) == 4, 'expected one row per variant, load and quantity');
    rows(i) = sprintf('%s (%s) & %.1f & %.1f & %.1f & %.1f \\\\', nm, ids(i), v);
end

L = [
"% Generated by make_rise_table.m from thermal_bias_table.csv; do not edit by hand."
"\begin{tabular}{@{}l S[table-format=2.1] S[table-format=2.1] S[table-format=-2.1] S[table-format=-2.1]@{}}"
"\toprule"
" & \multicolumn{2}{c}{Sensor minus air (\unit{\degreeCelsius})} & \multicolumn{2}{c}{Reported minus true RH (points)} \\"
"\cmidrule(lr){2-3}\cmidrule(l){4-5}"
"Enclosure (variant) & {\qty{800}{\watt\per\square\metre}} & {\qty{1000}{\watt\per\square\metre}} & {\qty{800}{\watt\per\square\metre}} & {\qty{1000}{\watt\per\square\metre}} \\"
"\midrule"
rows
"\bottomrule"
"\end{tabular}"
];
writelines(L, fullfile(outDir, 'predicted_rise_table.tex'));
end
