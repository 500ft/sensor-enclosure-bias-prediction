function make_interval_table(dataDir, outDir)
%MAKE_INTERVAL_TABLE Write the steady k = 2 interval table of docs/results.md as LaTeX.
%   Inputs in dataDir (analysis/output): thermal_bias_uncertainty.csv (nominal
%   and k = 2 interval per variant and operating point) and
%   thermal_bias_uncertainty.json (paired V0P minus V1 contrast per day point),
%   both written by analysis/steady_uncertainty.py. Output, a booktabs + siunitx
%   tabular fragment in outDir: thermal_bias_interval_table.tex, one row per
%   wind speed at 1000 W/m^2. Every number is read from those files; display
%   precision matches the Markdown table.

opts = detectImportOptions(fullfile(dataDir, 'thermal_bias_uncertainty.csv'), 'CommentStyle', '#');
opts = setvartype(opts, {'table', 'variant_id', 'variant_name'}, 'string');
T = readtable(fullfile(dataDir, 'thermal_bias_uncertainty.csv'), opts);
J = jsondecode(fileread(fullfile(dataDir, 'thermal_bias_uncertainty.json')));
C = J.contrasts_day;
G = 1000;
ids = ["V0", "V0P", "V1", "V2"];
heads = ["{\shortstack{Baseline closed\\box (V0)}}", "{\shortstack{Painted closed-box\\control (V0P)}}", ...
         "{\shortstack{Passive multi-plate\\shield (V1)}}", "{\shortstack{Actively aspirated\\reference (V2)}}", ...
         "{\shortstack{Painted box minus\\shield (V0P $-$ V1)}}"];
day = T(T.table == "day" & T.g_w_m2 == G, :);
W = unique(day.wind_m_s)';
cell3 = @(v, lo, hi) sprintf('\\num{%.2f} (\\num{%.2f} to \\num{%.2f})', v, lo, hi);
body = strings(0, 1);
for w = W
    parts = strings(1, 0);
    for id = ids
        r = day(day.variant_id == id & abs(day.wind_m_s - w) < 1e-9, :);
        assert(height(r) == 1, 'expected exactly one CSV row');
        parts(end + 1) = cell3(r.delta_t_degc, r.low_k2_degc, r.high_k2_degc); %#ok<AGROW>
    end
    k = find([C.g_w_m2] == G & abs([C.wind_m_s] - w) < 1e-9);
    assert(numel(k) == 1, 'expected exactly one contrast');
    parts(end + 1) = cell3(C(k).v0p_minus_v1_degc, C(k).low_k2_degc, C(k).high_k2_degc); %#ok<AGROW>
    body(end + 1, 1) = sprintf('%.1f & %s \\\\', w, strjoin(parts, ' & ')); %#ok<AGROW>
end
L = ["% Generated by make_interval_table.m from thermal_bias_uncertainty.csv and .json; do not edit by hand."; ...
    "\begin{tabular}{@{}S[table-format=1.1] *{5}{c}@{}}"; ...
    "\toprule"; ...
    sprintf(" & \\multicolumn{5}{c}{Sensor minus air at \\qty{%d}{\\watt\\per\\square\\metre}: nominal ($k = 2$ interval) (\\unit{\\degreeCelsius})} \\\\", G); ...
    "\cmidrule(l){2-6}"; ...
    "{\shortstack{Wind\\(\unit{\metre\per\second})}} & " + strjoin(heads, " & ") + " \\"; ...
    "\midrule"; body; "\bottomrule"; "\end{tabular}"];
writelines(L, fullfile(outDir, 'thermal_bias_interval_table.tex'));
end
